// Generates nginx/app-routes.conf from src/screen-map.js so the nginx route
// allowlist can never drift from the React Router table. Run through
// `npm run build` (or `npm run routes`); the Docker build copies the result.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROUTES } from '../src/screen-map.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'nginx/app-routes.conf');

// routes declared in App.jsx on top of the generated screen map: the article
// frame and the legacy URLs that LEGACY_ROUTES forwards to renamed screens
const extra = [
  '/landing/berita/:id',
  // shared invite links (/ref/CODE) open the register screen with the code
  '/ref/:code',
  '/deposit',
  '/deposit/qris',
  '/deposit/qris/konfirmasi',
  '/deposit/va',
  '/deposit/va/konfirmasi',
  '/tarik',
  '/tarik/konfirmasi',
  '/riwayat/deposit',
  '/riwayat/penarikan',
  '/riwayat/keuntungan',
  '/rewards/referral',
  '/fear-greed',
  '/profil/bank',
  '/profil/bank/1',
  '/profil/bank/2',
  '/profil/bank/3',
  '/profil/password',
];

// escape everything nginx's PCRE would read as syntax; ":param" becomes a
// single path segment so ids such as /landing/berita/86 still resolve
const escape = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const toRegex = (path) =>
  path
    .split('/')
    .map((segment) => (segment.startsWith(':') ? '[^/]+' : escape(segment)))
    .join('/');

const paths = [...new Set([...ROUTES.map((route) => route.path), ...extra])].sort();
const alternation = paths.map(toRegex).join('|');

const conf = `# generated by scripts/gen-nginx-routes.mjs from src/screen-map.js
# do not edit by hand — run \`npm run routes\` after adding a screen
map $uri $app_route {
    default 0;

    # the entry point redirects to /landing in the client
    ~^/$ 1;

    # only real screens get the SPA shell; anything else — dotfiles, backups,
    # scanner probes (/wp-admin, *.php) or unknown paths — must 404
    ~^(?:${alternation})/?$ 1;
}
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, conf);
console.log(`app-routes.conf: ${paths.length} routes`);
